package com.nya.app.ui

import android.content.Context
import androidx.compose.foundation.layout.*
import androidx.compose.foundation.rememberScrollState
import androidx.compose.foundation.verticalScroll
import androidx.compose.material3.AlertDialog
import androidx.compose.material3.Text
import androidx.compose.material3.TextButton
import androidx.compose.runtime.Composable
import androidx.compose.ui.Modifier
import androidx.compose.ui.text.font.FontWeight
import androidx.compose.ui.unit.dp
import androidx.compose.ui.unit.sp
import com.nya.app.ui.theme.LocalNya

class LegalDoc(val title: String, val sections: List<Pair<String, String>>)

private const val Notice = "Placeholder — final text to be provided by the client before release"

private val Contact = "Contact" to "Questions about this document: [contact email to be provided]."
private val Updated = "Last updated" to "[date to be provided]"

val PrivacyDoc = LegalDoc("Privacy policy", listOf(
    "Data we collect" to "Account email, your profile (name, date of birth, companion choices), memories (text and metadata), " +
        "chat messages, and basic device information.",
    "Where it is stored" to "On your device and in Google Firebase (US region), so your data syncs across your sessions.",
    "AI processing" to "Chat messages are sent to Google Gemini to generate Nya's replies.",
    Contact, Updated
))

val TermsDoc = LegalDoc("Terms of service", listOf(
    "Using Nya" to "You must be 18 or older. You are responsible for your account and for the content you save in the app.",
    "AI replies" to "Nya's replies are generated by AI and may be inaccurate. Do not rely on them for medical, legal or financial decisions.",
    "Plans and limits" to "Free and paid plans include daily message limits. Features may change or be unavailable at times.",
    Contact, Updated
))

/** Opens the hosted document when its URL is set and a browser exists; otherwise runs [fallback] to show the in-app text. */
fun Context.openLegal(url: String, fallback: () -> Unit) {
    if (url.isEmpty() || !openUrl(url)) fallback()
}

@Composable
private fun LegalText(doc: LegalDoc) {
    val c = LocalNya.current
    Text(Notice, color = NyaDanger, fontSize = 13.sp, fontWeight = FontWeight.SemiBold)
    doc.sections.forEach { (title, body) ->
        Text(title, color = c.tx, fontSize = 15.sp, fontWeight = FontWeight.SemiBold, modifier = Modifier.padding(top = 18.dp))
        Text(body, color = c.sb, fontSize = 14.sp, lineHeight = 21.sp, modifier = Modifier.padding(top = 4.dp))
    }
}

@Composable
private fun LegalScreen(doc: LegalDoc, onBack: () -> Unit) {
    Column(Modifier.fillMaxSize().nyaBg()) {
        XTop(doc.title, onBack)
        Column(Modifier.weight(1f).verticalScroll(rememberScrollState()).padding(horizontal = 20.dp)) {
            LegalText(doc)
            Spacer(Modifier.height(40.dp))
        }
    }
}

@Composable
fun PrivacyScreen(onBack: () -> Unit) = LegalScreen(PrivacyDoc, onBack)

@Composable
fun TermsScreen(onBack: () -> Unit) = LegalScreen(TermsDoc, onBack)

@Composable
fun LegalDialog(doc: LegalDoc, onDismiss: () -> Unit) {
    val c = LocalNya.current
    AlertDialog(
        onDismissRequest = onDismiss,
        containerColor = c.sf, titleContentColor = c.tx,
        title = { Text(doc.title) },
        text = { Column(Modifier.verticalScroll(rememberScrollState())) { LegalText(doc) } },
        confirmButton = { TextButton(onDismiss) { Text("Close", color = c.ac) } }
    )
}
